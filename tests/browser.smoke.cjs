const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844}});
  const errors=[];page.on('pageerror',e=>errors.push(e.stack||e.message));
  await page.route('https://example.invalid/**',route=>route.abort());
  await page.route('https://fonts.googleapis.com/**',route=>route.abort());
  await page.route('https://fonts.gstatic.com/**',route=>route.abort());
  await page.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});
  assert.equal(await page.locator('#layer-dashboard').isVisible(),true);
  assert.equal(await page.locator('#fbLayerNav').isVisible(),true);
  assert.equal(await page.locator('#fbLayerNav button').count(),6);
  assert.equal(await page.locator('#fbDashboardRefresh').count(),1);
  assert.equal(await page.locator('#layer-assistant').count(),1);
  if(await page.locator('#mcProductCatalog').count()===0){const diag=await page.evaluate(()=>({scripts:[...document.scripts].map(x=>x.src),ready:document.readyState,main:!!document.querySelector('main.wrap'),source:!!document.getElementById('sourcePanel'),shell:!!document.getElementById('fooladbanLayerShell')}));throw new Error('Product catalog missing. Page errors: '+errors.join('\\n')+' Diagnostics: '+JSON.stringify(diag))}
  await page.locator('#mcProductCatalog').waitFor({state:'attached'});
  assert.equal(await page.locator('#mcProductCatalog input[data-catalog-id]').count(),19);
  assert.equal(await page.locator('#mcSourceRegistry .mc-source').count(),7);
  assert.equal(await page.locator('#mcSourceRegistry').innerText().then(t=>t.includes('Trading Economics')),true);
  await page.locator('#fbLayerNav [data-layer-target="products"]').click();
  await page.locator('#mcProductCatalog input[data-catalog-id="rebar"]').check();
  assert.equal(await page.locator('#mcDashboardPicks').innerText().then(t=>t.includes('میلگرد')),true);
  await page.locator('#fbLayerNav [data-layer-target="dashboard"]').click();
  await page.locator('#mcDashboardPicks .mc-dashboard-card').first().click();
  assert.equal(await page.locator('#mcDashboardPicks .mc-dashboard-watch-title').first().isVisible(),true);
  await page.locator('#mcDashboardPicks [data-open-products]').first().click();
  await page.locator('#pCatalogSearch').fill('میلگرد');
  await page.locator('#pCatalogProduct').selectOption('rebar');
  assert.equal(await page.locator('#mcProductDetails').isVisible(),true);
  assert.equal(await page.locator('#pCatalogProduct').inputValue(),'rebar');
  assert.equal(await page.locator('#pGrade').isVisible(),true);
  assert.equal(await page.locator('#pSize').isVisible(),true);
  assert.equal(await page.locator('#pManufacturer').isVisible(),true);
  assert.equal(await page.locator('#pSourceRegistry').inputValue(),'ime');
  await page.locator('#pMarket').selectOption('جهانی');
  assert.equal(await page.locator('#pSourceRegistry option').count(),2);
  assert.equal(await page.locator('#pSourceRegistry').inputValue(),'tradingeconomics');
  await page.locator('#pMarket').selectOption('ایران');
  assert.equal(await page.locator('#pSourceRegistry').inputValue(),'ime');
  assert.equal(await page.locator('#mcQuickPrice').isVisible(),true);
  await page.locator('#pGrade').selectOption('A3');
  await page.locator('#pSize').selectOption('۱۶');
  await page.locator('#pUrl').fill('https://example.invalid/rebar');
  const validity=await page.locator('#productForm').evaluate(f=>({valid:f.checkValidity(),invalid:[...f.querySelectorAll(':invalid')].map(x=>x.id)}));
  assert.deepEqual(validity,{valid:true,invalid:[]});
  await page.locator('#productForm button[type=submit]').click();
  await page.waitForFunction(()=>JSON.parse(localStorage.getItem('fooladban.v1')||'{"products":[]}').products.length>0);
  await page.locator('#fbLayerNav [data-layer-target="dashboard"]').click();
  await page.locator('.prodname').filter({hasText:'میلگرد'}).waitFor();
  assert.equal(await page.locator('#mcQuickPrice').innerText().then(t=>t.includes('آخرین قیمت ثبت‌شده')),true);
  await page.locator('#mcDashboardPicks .mc-dashboard-card').first().click();
  await page.locator('#mcDashboardPicks [data-watch-action="edit"]').first().click();
  await page.locator('#pGrade').selectOption('A4');
  await page.locator('#productForm button[type=submit]').click();
  await page.locator('#fbLayerNav [data-layer-target="dashboard"]').click();
  await page.locator('#mcDashboardPicks .mc-dashboard-watch-title').first().waitFor();
  await page.locator('#mcProductDetails details.mc-advanced summary').click();
  await page.locator('#pMode').selectOption('selector');
  assert.equal(await page.locator('#selectorField').isVisible(),true);
  await page.locator('#fbLayerNav [data-layer-target="analysis"]').click();
  assert.equal(await page.locator('#layer-analysis').isVisible(),true);
  assert.equal(await page.locator('#layer-analysis .fb-compare-canvas').count(),1);
    await page.locator('#fbLayerNav [data-layer-target="settings"]').click();
  assert.equal(await page.locator('#layer-settings').isVisible(),true);
  assert.equal(await page.locator('#layer-settings .fb-settings-card').count(),15);
  assert.equal(await page.locator('#layer-settings').innerText().then(t=>t.includes('رنگ آیکون‌ها')),true);
  assert.equal(await page.locator('#layer-settings').innerText().then(t=>t.includes('ذخیره تنظیمات ظاهری')),true);
  assert.equal(await page.locator('#layer-settings .fb-about-brand img').getAttribute('src'),'./icon.svg');
  await page.locator('#layer-settings summary').filter({hasText:'قالب نمایش'}).click();
  await page.locator('#layer-settings summary').filter({hasText:'ترتیب لایه‌ها'}).click();
  assert.equal(await page.locator('.fb-layer-order').count(),6);
  await page.locator('#layer-settings .fb-setting-row select').first().selectOption('light');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
  assert.deepEqual(errors,[]);
  console.log('Browser smoke test passed: six-layer navigation, product cards with monitoring, selected product registration, settings, theme, layer order and no runtime exceptions');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
